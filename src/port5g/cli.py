def cmd_geometry_check(a):
    from . import geometry
    cfg = load_config(warn=False)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        site = geometry.load_site(cfg)
    print(f"placeholder: {site.placeholder}; area {site.area_ha:.1f} ha; quay {site.quay.length:.0f} m")
    for z in site.zones:
        print(f"  zone {z}: {site.zones[z].area/1e4:.1f} ha, clutter density r={site.clutter_density(z):.2f}")
    if not 70 <= site.area_ha <= 110:
        print("WARNING: area outside 70-110 ha (brief §1.1 range)")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="port5g")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run"); r.add_argument("--seed", type=int, default=None); r.set_defaults(fn=cmd_run)
    sub.add_parser("figures").set_defaults(fn=cmd_figures)
    s = sub.add_parser("assumptions"); s.add_argument("--strict", action="store_true"); s.set_defaults(fn=cmd_assumptions)
    sub.add_parser("anchors").set_defaults(fn=cmd_anchors)
    sub.add_parser("geometry-check").set_defaults(fn=cmd_geometry_check)
    a = ap.parse_args(argv); a.fn(a)


if __name__ == "__main__":
    main()
